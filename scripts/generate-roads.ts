// Gzips the exported street GeoJSON and writes it as a base64 string module.
// The page decompresses it in the browser (DecompressionStream), which keeps the
// standalone HTML small without changing the GeoJSON format.
const source = "osm_data/richardstrasse-bochum.geojson";
const gzipped = Bun.gzipSync(new Uint8Array(await Bun.file(source).arrayBuffer()));
const base64 = Buffer.from(gzipped).toString("base64");

await Bun.write(
  "src/generated/roads.ts",
  `// Generated by scripts/generate-roads.ts from ${source}. Do not edit.\nexport const roadsGzipBase64 = "${base64}";\n`,
);
console.log(`Wrote src/generated/roads.ts (${gzipped.byteLength} bytes gzipped)`);
